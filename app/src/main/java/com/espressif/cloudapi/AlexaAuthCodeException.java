package com.espressif.cloudapi;

/**
 * Exception thrown when the Alexa "get auth code" API returns an unexpected HTTP response.
 * It carries the HTTP status code of that response, e.g. for logging or for callers that need
 * to react to specific codes.
 */
public class AlexaAuthCodeException extends RuntimeException {

    private final int statusCode;

    public AlexaAuthCodeException(int statusCode, String message) {
        super(message);
        this.statusCode = statusCode;
    }

    public int getStatusCode() {
        return statusCode;
    }
}
